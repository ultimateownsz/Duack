"""Split a monolithic markdown plan into a shared doc and per-slice specs.

A large plan written as one ``PLAN.md`` with ``## N. ...`` sections can be handed
in as a folder: ``README.md`` (index), ``SHARED.md`` (everything that is not a
slice), and ``<slug>/PLAN.md`` for each ``Slice X - Name`` section. The input is
left in place unless ``--remove-input`` is passed, and existing output is never
clobbered unless ``--force`` is passed.

    python tools/plan_split.py docs/plans/vnext/PLAN.md \
        --slug A=voice-concurrency --slug B=2d-spatial
"""

import argparse
import re
import sys
from pathlib import Path

HEADING_RE = re.compile(r"^##[ \t]+(.+?)[ \t]*$", re.M)
H1_RE = re.compile(r"^#[ \t]+(.+?)[ \t]*$", re.M)
SLICE_RE = re.compile(r"Slice\s+([A-Za-z0-9]+)\s*[—–-]\s*(.+)$", re.I)


class PlanSplitError(Exception):
    """Raised when the input cannot be split safely."""


def _slugify(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _parse(text):
    matches = list(HEADING_RE.finditer(text))
    if not matches:
        raise PlanSplitError("no '##' sections found; nothing to split")
    preamble = text[:matches[0].start()].rstrip()
    sections = []
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections.append(text[match.start():end].rstrip())
    return preamble, sections


def _slice_info(title, slugs):
    match = SLICE_RE.search(title)
    if match is None:
        return None
    marker, name = match.group(1), match.group(2).strip()
    overrides = slugs or {}
    slug = overrides.get(marker) or overrides.get(marker.lower()) or _slugify(name)
    if not slug:
        raise PlanSplitError(f"empty slug for slice {marker}")
    return marker, name, slug


def split_plan(plan_path, out_dir=None, *, slugs=None, force=False, remove_input=False):
    """Split ``plan_path`` into ``out_dir`` and return a summary of what was written.

    Only ``##`` sections whose title contains ``Slice X - Name`` become slice
    folders; every other section keeps its full text (including its ``##``
    heading) in ``SHARED.md`` so numbered cross-references still resolve.
    """
    plan_path = Path(plan_path)
    out_dir = Path(out_dir) if out_dir is not None else plan_path.parent
    preamble, sections = _parse(plan_path.read_text(encoding="utf-8"))

    shared = []
    slices = []
    for section in sections:
        title = section.splitlines()[0][3:]
        info = _slice_info(title, slugs)
        if info is None:
            shared.append(section)
        else:
            marker, name, slug = info
            body = section.split("\n", 1)[1].strip() if "\n" in section else ""
            slices.append((slug, marker, name, body))

    if not slices:
        raise PlanSplitError("no slice sections found; nothing to split")

    seen = set()
    for slug, _, _, _ in slices:
        if slug in seen:
            raise PlanSplitError(f"duplicate slug {slug!r}; pass an explicit --slug override")
        seen.add(slug)

    h1 = H1_RE.search(preamble)
    plan_title = h1.group(1) if h1 else "Plan"

    shared_text = preamble + "\n\n" + "\n\n".join(shared) + "\n"
    rows = "\n".join(
        f"| Slice {marker} — {name} | [{slug}/]({slug}/) | draft | |"
        for slug, marker, name, _ in slices
    )
    index_text = (
        f"# {plan_title} — plan index\n\n"
        "Generated by `tools/plan_split.py`. Review the rows and replace `draft`\n"
        "with real statuses before handing the plan in.\n\n"
        "Shared evidence, ADRs, gates, standards, and math live in [`SHARED.md`](SHARED.md).\n\n"
        "## Slices\n\n"
        "| Slice | Folder | Status | Notes |\n"
        "| --- | --- | --- | --- |\n"
        + rows + "\n"
    )

    outputs = {
        out_dir / "SHARED.md": shared_text,
        out_dir / "README.md": index_text,
    }
    for slug, marker, name, body in slices:
        outputs[out_dir / slug / "PLAN.md"] = (
            f"# {plan_title} — Slice {marker} — {name}\n\n"
            "Index: `../README.md` · Shared evidence/ADRs/gates/math: `../SHARED.md`\n\n"
            "`STATUS.md` (state and open questions) and `slice.md` (decisions)\n"
            "are added when this slice starts.\n\n---\n\n"
            + body + "\n"
        )

    existing = [path for path in outputs if path.exists()]
    if existing and not force:
        raise PlanSplitError(
            "refusing to overwrite existing output: " + ", ".join(str(p) for p in existing)
        )

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if remove_input:
        plan_path.unlink()

    return {
        "shared": out_dir / "SHARED.md",
        "index": out_dir / "README.md",
        "slices": [(slug, marker, name) for slug, marker, name, _ in slices],
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description="Split a large markdown plan into per-slice files.")
    parser.add_argument("plan", type=Path, help="monolithic PLAN.md to split")
    parser.add_argument("--out", type=Path, help="output directory (default: the plan's directory)")
    parser.add_argument(
        "--slug", action="append", default=[], metavar="MARKER=SLUG",
        help="override a slice's folder slug, e.g. --slug A=voice-concurrency",
    )
    parser.add_argument("--force", action="store_true", help="overwrite existing generated files")
    parser.add_argument(
        "--remove-input", action="store_true", help="delete the input plan after a successful split"
    )
    args = parser.parse_args(argv)

    slugs = {}
    for item in args.slug:
        if "=" not in item:
            parser.error(f"--slug expects MARKER=SLUG, got {item!r}")
        key, value = item.split("=", 1)
        slugs[key.strip()] = value.strip()

    try:
        summary = split_plan(
            args.plan, args.out, slugs=slugs, force=args.force, remove_input=args.remove_input
        )
    except (PlanSplitError, OSError) as exc:
        parser.error(str(exc))

    print(f"Wrote {summary['shared']}, {summary['index']}, and "
          f"{len(summary['slices'])} slice spec(s).")
    print("Review the index, fill in statuses, and add STATUS.md/slice.md when each slice starts.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
